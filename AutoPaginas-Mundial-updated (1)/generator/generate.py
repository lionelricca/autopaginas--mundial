"""Generate static pages for the AutoPaginas Mundial project.

This script reads a configuration file (config.json) describing
the different categories to generate. Each category entry
specifies a slug (used for the filename), a title, a description,
the type of content (bios, names or phrases), the language and
optionally a style for phrases.

Running this script will populate the ``docs`` directory with
HTML pages for each category and an index page linking to them.

The generated lists are created on‑the‑fly using simple
combinatorial logic so the output changes with each run. For
example, names are generated by combining an adjective with a
noun, bios are composed of an introduction, a descriptor and a
closing sentence, and phrases are built from two complementary
halves.

The goal of this project is to demonstrate how a self‑updating
site could be built without any external APIs. You can add or
modify categories in ``config.json`` to further tailor the
generated content. To deploy the site on GitHub Pages you can
commit this repository to a public GitHub repository and enable
Pages on the ``docs`` directory.
"""

