def random_name(language: str) -> str:
    """Generate a random team or username depending on the language."""
    if language == "es":
        return f"{random.choice(ADJECTIVES_ES)} {random.choice(NOUNS_ES)}"
    # default to English
    return f"{random.choice(ADJECTIVES_EN)} {random.choice(NOUNS_EN)}"


def random_bio(language: str) -> str:
    """Generate a random bio composed of intro, descriptor and closer."""
    if language == "es":
        intro = random.choice(BIO_INTROS_ES)
        descriptor = random.choice(BIO_DESCRIPTORS_ES)
        closer = random.choice(BIO_CLOSERS_ES)
    else:
        intro = random.choice(BIO_INTROS_EN)
        descriptor = random.choice(BIO_DESCRIPTORS_EN)
        closer = random.choice(BIO_CLOSERS_EN)
    # Use a comma after the descriptor to mirror the English style. Spanish
    # grammar tolerates the same structure for these simple sentences.
    return f"{intro} {descriptor}, {closer}"


def random_phrase(language: str, style: str = "inspirational") -> str:
    """Generate a random phrase based on language and style (inspirational or funny)."""
    style_key = style if style in PHRASE_INTROS_EN else "inspirational"
    if language == "es":
        intro_pool = PHRASE_INTROS_ES.get(style_key, PHRASE_INTROS_ES["inspirational"])
        closer_pool = PHRASE_CLOSERS_ES.get(style_key, PHRASE_CLOSERS_ES["inspirational"])
    else:
        intro_pool = PHRASE_INTROS_EN.get(style_key, PHRASE_INTROS_EN["inspirational"])
        closer_pool = PHRASE_CLOSERS_EN.get(style_key, PHRASE_CLOSERS_EN["inspirational"])
    return f"{random.choice(intro_pool)} {random.choice(closer_pool)}"


def generate_items(category: dict) -> list[str]:
    """Generate a list of 100 items for a given category."""
    kind = category.get("kind")
    lang = category.get("language", "en")
    style = category.get("style", "inspirational")
    items: list[str] = []
    if kind == "names":
        items = [random_name(lang) for _ in range(100)]
    elif kind == "bios":
        items = [random_bio(lang) for _ in range(100)]
    elif kind == "phrases":
        items = [random_phrase(lang, style) for _ in range(100)]
    return items


def create_page(category: dict, items: list[str]) -> None:
    """Create an HTML page for a category with the generated items.

    Pages are written into the top‑level ``docs`` directory next to
    the ``generator`` folder. Using an absolute path relative to this
    script’s parent directory ensures the output location is
    consistent regardless of the current working directory.
    """
    slug = category["slug"]
    title = category["title"]
    description = category.get("description", "")
    language = category.get("language", "en")
    # Build list items HTML
    list_html = "\n        ".join(f"<li>{item}</li>" for item in items)
    # Choose placeholder text based on language
    search_placeholder = "Buscar..." if language == "es" else "Search..."
    # Build a donation block HTML with copy button. The copy
    # functionality uses the Clipboard API available in modern
    # browsers. If unsupported it simply does nothing.
    # Build a donation section that does not rely on any third‑party widgets.  In
    # addition to showing the wallet address and providing a copy button, we
    # also include an explicit `ethereum:` link.  Clicking this link will
    # trigger supported wallets (e.g. MetaMask) to prepare a transfer to the
    # specified address.  This approach keeps the site entirely self‑hosted
    # and avoids dependencies on external payment providers.
    donation_html = f"""
    <div class=\"adslot\">
      <p><strong>¿Te gusta este sitio?</strong> Si quieres apoyarlo, puedes enviar
      una contribución directamente a la billetera del proyecto:</p>
      <p><code>{WALLET_ADDRESS}</code></p>
      <button onclick=\"navigator.clipboard.writeText('{WALLET_ADDRESS}')\">Copiar dirección</button>
      <p><a href=\"ethereum:{WALLET_ADDRESS}\" target=\"_blank\">Abrir en tu monedero (MetaMask u otro)</a></p>
    </div>
    """
    page_html = f"""<!DOCTYPE html>
<html lang=\"{language}\">
<head>
    <meta charset=\"utf-8\">
    <title>{title}</title>
    <meta name=\"description\" content=\"{description}\">
    <meta name=\"viewport\" content=\"width=device-width, initial-scale=1.0\">
    <link rel=\"stylesheet\" href=\"assets/style.css\">
    <script>
    function filterList() {{
        const input = document.getElementById('searchInput');
        const filter = input.value.toLowerCase();
        const items = document.querySelectorAll('#items li');
        items.forEach(item => {{
            const text = item.textContent.toLowerCase();
            item.style.display = text.includes(filter) ? '' : 'none';
        }});
    }}
    </script>
</head>
<body>
    <h1>{title}</h1>
    <p>{description}</p>
    <input type=\"text\" id=\"searchInput\" class=\"search\" placeholder=\"{search_placeholder}\" oninput=\"filterList()\">
    <div class=\"adslot\">Zona de monetización</div>
    <ul id=\"items\">
        {list_html}
    </ul>
    {donation_html}
    <p><a href=\"index.html\">Inicio / Home</a></p>
</body>
</html>"""
    # Determine the base directory (one level up from this file)
    base_dir = Path(__file__).resolve().parents[1]
    docs_dir = base_dir / 'docs'
    docs_dir.mkdir(parents=True, exist_ok=True)
    file_path = docs_dir / f"{slug}.html"
    with file_path.open('w', encoding='utf-8') as f:
        f.write(page_html)


